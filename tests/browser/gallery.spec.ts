import { expect, test } from '@playwright/test'

test('visitor navigates nested folders and finds filenames across the entire gallery', async ({ page }) => {
  await page.goto('/', { waitUntil: 'domcontentloaded' })
  await expect(page.getByRole('button', { name: 'Mở ảnh Bình minh.jpg', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Biển & đảo', exact: true }).click()
  await page.getByRole('button', { name: 'Ngày yên', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Mở ảnh Biển lặng.png', exact: true })).toBeVisible()
  await page.getByRole('navigation', { name: 'Vị trí thư mục' }).getByRole('button', { name: 'Bộ sưu tập', exact: true }).click()
  await page.getByRole('button', { name: 'Album trống', exact: true }).click()
  await expect(page.getByText('Folder này chưa có ảnh')).toBeVisible()
  await page.getByRole('searchbox', { name: 'Tìm theo tên file trong toàn thư viện' }).fill('Biển')
  await expect(page.getByRole('button', { name: 'Mở ảnh Biển chiều.webp', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Mở ảnh Biển lặng.png', exact: true })).toBeVisible()
  await expect(page.getByText('Bí mật.pdf')).toHaveCount(0)
})

test('lightbox fits the image, follows the current results, handles unavailable originals and downloads an available file', async ({ page }) => {
  const requests: string[] = []
  page.on('request', (request) => requests.push(request.url()))
  await page.goto('/', { waitUntil: 'domcontentloaded' })
  const opener = page.getByRole('button', { name: 'Mở ảnh Bình minh.jpg', exact: true })
  await expect(opener).toBeVisible()
  await page.getByRole('button', { name: 'Xem thêm ảnh', exact: false }).click()
  await expect(page.getByRole('button', { name: 'Mở ảnh Ảnh thiếu thumbnail.png', exact: true })).toBeVisible()
  expect(requests.some((url) => /\/preview|\/download|alt=media/.test(url))).toBe(false)
  await opener.click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toBeVisible()
  const image = dialog.getByRole('img', { name: 'Bình minh.jpg', exact: true })
  await expect(image).toBeVisible()
  await expect.poll(() => image.evaluate((element) => (element as HTMLImageElement).naturalWidth)).toBeGreaterThan(0)
  const bounds = await image.boundingBox()
  expect(bounds!.width).toBeLessThanOrEqual(page.viewportSize()!.width)
  expect(bounds!.height).toBeLessThanOrEqual(page.viewportSize()!.height)
  await page.keyboard.press('ArrowRight')
  await expect(dialog.getByRole('heading', { name: 'Ảnh thiếu thumbnail.png', exact: true })).toBeVisible()
  await expect(dialog.getByText('Ảnh xem trước chưa khả dụng.')).toBeVisible()
  await dialog.getByRole('button', { name: 'Tải ảnh gốc', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('Ảnh gốc không khả dụng')
  await page.keyboard.press('ArrowRight')
  await expect(dialog.getByRole('heading', { name: 'Bình minh.jpg', exact: true })).toBeVisible()
  const downloadEvent = page.waitForEvent('download')
  await dialog.getByRole('button', { name: 'Tải ảnh gốc', exact: true }).click()
  expect((await downloadEvent).suggestedFilename()).toBe('Bình minh.jpg')
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(opener).toBeFocused()
})

test('Vietnamese gallery persists its theme and remains within the viewport', async ({ page }, testInfo) => {
  const failures: string[] = []
  page.on('pageerror', (error) => failures.push(error.message))
  await page.goto('/', { waitUntil: 'domcontentloaded' })
  await expect(page.getByRole('button', { name: 'Mở ảnh Bình minh.jpg', exact: true })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('gallery-light.png'), fullPage: true })
  await page.getByRole('button', { name: 'Bật giao diện tối', exact: true }).click()
  await page.reload({ waitUntil: 'domcontentloaded' })
  await expect(page.getByRole('button', { name: 'Bật giao diện sáng', exact: true })).toBeVisible()
  expect(await page.locator('html').getAttribute('lang')).toBe('vi')
  expect(await page.locator('html').getAttribute('data-theme')).toBe('dark')
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await expect(page.getByRole('button', { name: 'Mở ảnh Bình minh.jpg', exact: true })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('gallery-dark.png'), fullPage: true })
  expect(failures).toEqual([])
})

test('visitor sees loading, recoverable errors and rate limiting, then retries successfully', async ({ page }) => {
  await page.goto('http://127.0.0.1:5175/', { waitUntil: 'domcontentloaded' })
  await expect(page.getByRole('status')).toContainText('Đang tải ảnh')
  await expect(page.getByRole('alert')).toContainText('Chưa thể tải thư viện')
  await page.getByRole('button', { name: 'Thử lại', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Thư viện cần nghỉ một chút')
  await page.getByRole('button', { name: 'Thử lại', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Mở ảnh Bình minh.jpg', exact: true })).toBeVisible()
  await expect(page.getByRole('alert')).toHaveCount(0)
})
