import { expect, test } from '@playwright/test'

test('first child album opens automatically and the parent folder is absent from album navigation', async ({ page }) => {
  await page.goto('/', { waitUntil: 'domcontentloaded' })
  const albums = page.getByRole('navigation', { name: 'Các album cưới' })
  await expect(albums.getByRole('button', { name: 'Biển & đảo', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByRole('button', { name: 'Mở ảnh Biển chiều.webp', exact: true })).toBeVisible()
  await expect(albums.getByRole('button', { name: 'Album trống', exact: true })).toBeVisible()
  await expect(albums.getByRole('button', { name: 'Lễ thành hôn', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Toàn bộ album', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Bộ sưu tập', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Mở ảnh Bình minh.jpg', exact: true })).toHaveCount(0)
})

test('navigation back returns through nested albums and the overview without exposing root photos', async ({ page }) => {
  await page.goto('/', { waitUntil: 'domcontentloaded' })
  await page.getByRole('button', { name: 'Mở album Ngày yên', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Mở ảnh Biển lặng.png', exact: true })).toBeVisible()
  const header = page.getByRole('banner')
  await header.getByRole('button', { name: 'Quay lại album trước', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Mở ảnh Biển chiều.webp', exact: true })).toBeVisible()
  await header.getByRole('button', { name: 'Quay lại danh sách album', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Mở album Biển & đảo', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Mở ảnh Bình minh.jpg', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Mở album Album trống', exact: true }).click()
  await expect(page.getByText('Album này chưa có ảnh')).toBeVisible()
  await page.getByRole('searchbox').fill('Biển')
  await expect(page.getByRole('button', { name: 'Mở ảnh Biển lặng.png', exact: true })).toBeVisible()
  await header.getByRole('button', { name: 'Quay lại album', exact: true }).click()
  await expect(page.getByRole('searchbox')).toHaveValue('')
  await expect(page.getByText('Album này chưa có ảnh')).toBeVisible()
})

test('fixed back-to-top remains reachable after scrolling and is hidden behind the lightbox', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/', { waitUntil: 'domcontentloaded' })
  const photo = page.getByRole('button', { name: 'Mở ảnh Biển chiều.webp', exact: true })
  await photo.scrollIntoViewIfNeeded()
  const top = page.getByRole('button', { name: 'Lên đầu trang', exact: true })
  await expect(top).toBeVisible()
  expect(await top.evaluate((element) => getComputedStyle(element).position)).toBe('fixed')
  const bounds = await top.boundingBox()
  expect(bounds!.width).toBeGreaterThanOrEqual(44)
  expect(bounds!.height).toBeGreaterThanOrEqual(44)
  expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(page.viewportSize()!.height)
  expect(await page.getByRole('banner').evaluate((element) => element.getBoundingClientRect().top)).toBe(0)
  await photo.click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(top).toHaveCount(0)
  await page.getByRole('button', { name: 'Đóng ảnh', exact: true }).click()
  await expect(top).toBeVisible()
  await top.click()
  await expect.poll(() => page.evaluate(() => window.scrollY)).toBe(0)
})

test('phone, tablet and desktop layouts have readable controls, visible photos and a working favicon', async ({ page }) => {
  await page.goto('/', { waitUntil: 'domcontentloaded' })
  await expect(page.getByRole('button', { name: 'Mở ảnh Biển chiều.webp', exact: true })).toBeVisible()
  for (const width of [320, 834, 1440]) {
    await page.setViewportSize({ width, height: 1000 })
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    const input = page.getByRole('searchbox')
    expect(await input.evaluate((element) => parseFloat(getComputedStyle(element).fontSize))).toBeGreaterThanOrEqual(16)
    const image = page.getByRole('img', { name: 'Biển chiều.webp', exact: true })
    await image.scrollIntoViewIfNeeded()
    await expect.poll(() => image.evaluate((element) => (element as HTMLImageElement).naturalWidth)).toBeGreaterThan(0)
    const bounds = await image.boundingBox()
    expect(bounds!.height).toBeGreaterThan(100)
    if (width === 1440) expect(await page.locator('.photo-meta h3').first().evaluate((element) => parseFloat(getComputedStyle(element).fontSize))).toBeGreaterThanOrEqual(16)
  }
  const favicon = await page.request.get('/favicon.svg')
  expect(favicon.ok()).toBe(true)
  expect(favicon.headers()['content-type']).toContain('image/svg+xml')
})
